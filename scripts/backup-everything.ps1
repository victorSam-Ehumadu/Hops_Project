<#
.SYNOPSIS
  One offline copy of everything Hops needs to be rebuilt and shipped again.

.DESCRIPTION
  backup-db.ps1 covers the database, which is the only state that does not
  live on a device. It is not a backup of the PROJECT. This is.

  Three of the four things here cannot be regenerated from anything else:

    client\.env            gitignored. Without it the app will not build.
    debug.keystore         signs the release APK. See the warning below.
    the database dump      every account, report and moderation record.

  The fourth, the source tree, is also on GitHub — but this copies it with
  its .git directory, so you keep the full history with no GitHub account,
  no network, and no dependency on that repository continuing to exist.

  THE KEYSTORE IS THE ONE THAT ENDS PROJECTS.

  client\android\app\build.gradle.kts signs release builds with the DEBUG
  keystore. Android refuses to install an update signed by a different key.
  Lose that file and no future build can ever update an existing install:
  every user has to uninstall first, and since Hops keeps its data on the
  device and nowhere else, uninstalling destroys all of it — their messages,
  contacts, tasks, carrots. There is no recovery and no workaround. It is
  2.6 KB and it is the most valuable file in this project.

  WHAT THIS DELIBERATELY DOES NOT CAPTURE

    Supabase Edge Function secrets  RESEND_API_KEY, HOPS_EMAIL_FROM,
                                    HOPS_APPEALS_EMAIL. They live in
                                    Supabase and pg_dump does not see them.
    The two Vault keys              hops_email_encryption_key and
                                    hops_email_blind_index_key. A normal
                                    dump cannot read the vault schema.

  Both are listed in the manifest as a reminder to record them somewhere
  else, because discovering they are gone is a quiet, delayed failure.

.PARAMETER Destination
  Where to write the backup. Default: a dated folder on the Desktop.
  Point this at a USB stick or a cloud-synced folder — a backup on the
  same disk does not survive the failure you are backing up against.

.PARAMETER WithDatabase
  Also take a FRESH database dump by calling backup-db.ps1, which will
  prompt for the connection URI. Without this switch, whatever dumps are
  already in backups\ are copied instead, and their age is reported.

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\scripts\backup-everything.ps1 -Destination E:\HopsBackup

.EXAMPLE
  powershell -ExecutionPolicy Bypass -File .\scripts\backup-everything.ps1 -WithDatabase
#>

[CmdletBinding()]
param(
  [string] $Destination,
  [switch] $WithDatabase
)

# Continue, not Stop: robocopy and pg_dump write to stderr in the normal
# course of working, and Windows PowerShell 5.1 turns each of those lines
# into a terminating error under Stop. Exit codes are checked explicitly
# instead. See the same note in verify-backup.ps1.
$ErrorActionPreference = "Continue"

$repoRoot = Split-Path -Parent $PSScriptRoot
$stamp    = Get-Date -Format "yyyyMMdd-HHmmss"

if ([string]::IsNullOrWhiteSpace($Destination)) {
  $desktop = [Environment]::GetFolderPath("Desktop")
  $Destination = Join-Path $desktop "HopsBackup_$stamp"
}

Write-Host ""
Write-Host "Hops full backup" -ForegroundColor Cyan
Write-Host "  from : $repoRoot"
Write-Host "  to   : $Destination"
Write-Host ""

New-Item -ItemType Directory -Force -Path $Destination | Out-Null

$warnings = New-Object System.Collections.Generic.List[string]
$manifest = New-Object System.Collections.Generic.List[string]
$manifest.Add("Hops backup")
$manifest.Add("taken     : $(Get-Date -Format 'yyyy-MM-dd HH:mm:ss')")
$manifest.Add("from      : $repoRoot")
$manifest.Add("machine   : $env:COMPUTERNAME")
$manifest.Add("")

function Add-Manifest([string] $label, [string] $path) {
  if (Test-Path $path) {
    $item = Get-Item $path
    $hash = (Get-FileHash $path -Algorithm SHA256).Hash
    $manifest.Add(("{0,-22} {1,10:N0} bytes  {2}" -f $label, $item.Length, $hash))
  }
}

# ── 1. Source tree, with history ──────────────────────────────────────────
# Excludes build output and the dumps folder: build/ is regenerated by a
# build and is ~1 GB, and backups/ is copied separately below so the
# manifest can report on it.
Write-Host "[1/5] Source tree (including .git)..." -ForegroundColor Yellow
$repoDest = Join-Path $Destination "repo"
robocopy $repoRoot $repoDest /E /NFL /NDL /NJH /NJS /NP `
  /XD build .dart_tool .gradle backups node_modules | Out-Null

# Robocopy's exit codes are a bit field, not a status. 0-7 all mean success
# (1 = files copied, 2 = extra files, 4 = mismatched). 8 and above are real
# failures. Treating any non-zero as an error here would fail every run.
if ($LASTEXITCODE -ge 8) {
  $warnings.Add("robocopy reported failures (exit $LASTEXITCODE) - the source copy may be incomplete")
} else {
  Write-Host "      done." -ForegroundColor Green
}
$global:LASTEXITCODE = 0

# ── 2. client\.env ────────────────────────────────────────────────────────
Write-Host "[2/5] client\.env..." -ForegroundColor Yellow
$envSrc = Join-Path $repoRoot "client\.env"
if (Test-Path $envSrc) {
  Copy-Item $envSrc (Join-Path $Destination "client.env.backup") -Force
  Add-Manifest "client/.env" $envSrc
  Write-Host "      done." -ForegroundColor Green
} else {
  $warnings.Add("client\.env NOT FOUND - the app cannot be built without it")
  Write-Host "      MISSING." -ForegroundColor Red
}

# ── 3. The signing keystore ───────────────────────────────────────────────
Write-Host "[3/5] Signing keystore..." -ForegroundColor Yellow
$ksSrc = Join-Path $env:USERPROFILE ".android\debug.keystore"
if (Test-Path $ksSrc) {
  Copy-Item $ksSrc (Join-Path $Destination "debug.keystore") -Force
  Add-Manifest "debug.keystore" $ksSrc
  Write-Host "      done." -ForegroundColor Green
} else {
  $warnings.Add("debug.keystore NOT FOUND at $ksSrc - releases are signed with it; without it no future build can update an installed app")
  Write-Host "      MISSING." -ForegroundColor Red
}

# ── 4. Database ───────────────────────────────────────────────────────────
Write-Host "[4/5] Database dump..." -ForegroundColor Yellow
if ($WithDatabase) {
  Write-Host "      Running backup-db.ps1 (it will ask for the connection URI)."
  & (Join-Path $PSScriptRoot "backup-db.ps1")
}

$dumpDir = Join-Path $repoRoot "backups"
$dumps = @()
if (Test-Path $dumpDir) {
  $dumps = @(Get-ChildItem $dumpDir -Filter *.sql | Sort-Object LastWriteTime -Descending)
}
if ($dumps.Count -gt 0) {
  $dbDest = Join-Path $Destination "database"
  New-Item -ItemType Directory -Force -Path $dbDest | Out-Null
  foreach ($d in $dumps) { Copy-Item $d.FullName $dbDest -Force }
  $newest = $dumps[0]
  Add-Manifest "newest dump" $newest.FullName
  $ageDays = [int]((Get-Date) - $newest.LastWriteTime).TotalDays
  $manifest.Add(("{0,-22} {1}" -f "newest dump date", $newest.LastWriteTime))
  Write-Host "      $($dumps.Count) dump(s) copied, newest is $ageDays day(s) old." -ForegroundColor Green
  if ($ageDays -gt 7 -and -not $WithDatabase) {
    $warnings.Add("newest database dump is $ageDays days old - re-run with -WithDatabase for a current one")
  }
} else {
  $warnings.Add("no database dumps found in backups\ - run scripts\backup-db.ps1, or re-run this with -WithDatabase")
  Write-Host "      none found." -ForegroundColor Red
}

# ── 5. Built APKs, if any ─────────────────────────────────────────────────
# Convenience, not necessity: an APK is reproducible from the source, the
# .env and the keystore above. What is worth keeping is the EXACT artifact
# that was released or demonstrated, byte for byte, so "which build was on
# the phone that day" has an answer.
Write-Host "[5/5] Built APKs..." -ForegroundColor Yellow
$apkDest = Join-Path $Destination "apk"
$apkFound = 0
foreach ($candidate in @("client\build\hops.apk",
                         "client\build\hops-admin.apk",
                         "client\build\app\outputs\flutter-apk\app-release.apk")) {
  $p = Join-Path $repoRoot $candidate
  if (Test-Path $p) {
    if ($apkFound -eq 0) { New-Item -ItemType Directory -Force -Path $apkDest | Out-Null }
    Copy-Item $p $apkDest -Force
    Add-Manifest (Split-Path $candidate -Leaf) $p
    $apkFound++
  }
}
if ($apkFound -gt 0) {
  Write-Host "      $apkFound APK(s) copied." -ForegroundColor Green
} else {
  Write-Host "      none found (not a problem - they rebuild from source)." -ForegroundColor DarkGray
}

# ── Manifest ──────────────────────────────────────────────────────────────
$manifest.Add("")
$manifest.Add("NOT IN THIS BACKUP - record these somewhere else:")
$manifest.Add("  Supabase Edge Function secrets: RESEND_API_KEY, HOPS_EMAIL_FROM,")
$manifest.Add("    HOPS_APPEALS_EMAIL, HOPS_EMAIL_REPLY_TO")
$manifest.Add("  Supabase Vault keys: hops_email_encryption_key,")
$manifest.Add("    hops_email_blind_index_key")
$manifest.Add("")
$manifest.Add("TO RESTORE ONTO A NEW MACHINE:")
$manifest.Add("  1. Copy repo\ to wherever you want the project.")
$manifest.Add("  2. Copy client.env.backup to client\.env")
$manifest.Add("  3. Copy debug.keystore to %USERPROFILE%\.android\debug.keystore")
$manifest.Add("     Do this BEFORE building, or the APK is signed with a new key")
$manifest.Add("     and will not install over anyone's existing Hops.")
$manifest.Add("  4. cd client; flutter pub get")
$manifest.Add("  5. Database: see scripts\verify-backup.ps1 for restoring a dump.")
$manifest.Add("")
if ($warnings.Count -gt 0) {
  $manifest.Add("WARNINGS AT BACKUP TIME:")
  foreach ($w in $warnings) { $manifest.Add("  - $w") }
}

$manifestPath = Join-Path $Destination "MANIFEST.txt"
Set-Content -Path $manifestPath -Value $manifest -Encoding utf8

# ── Report ────────────────────────────────────────────────────────────────
Write-Host ""
if ($warnings.Count -gt 0) {
  Write-Host "Finished WITH WARNINGS:" -ForegroundColor Red
  foreach ($w in $warnings) { Write-Host "  - $w" -ForegroundColor Red }
} else {
  Write-Host "Finished. Nothing missing." -ForegroundColor Green
}
Write-Host ""
Write-Host "  $Destination"
Write-Host "  (see MANIFEST.txt for contents, hashes and restore steps)"
Write-Host ""
Write-Host "This folder contains your Supabase key, your signing key, and a" -ForegroundColor Yellow
Write-Host "dump holding every password hash and the full moderation log." -ForegroundColor Yellow
Write-Host "Store it like a password, not like a project folder." -ForegroundColor Yellow
Write-Host ""
